// Copies contract ABIs from the Foundry build into @whitepay/shared, so the app never hand-types an ABI.
// Run after `npm run contracts:build`:  npx tsx scripts/abi-sync.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"

const CONTRACTS = ["ProtectedEscrow"]
const root = new URL("..", import.meta.url).pathname
const outDir = join(root, "packages/shared/src/abi")
mkdirSync(outDir, { recursive: true })

for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"))
  const body =
    `// Generated by scripts/abi-sync.ts from contracts/out/${name}.sol/${name}.json. Do not edit by hand.\n` +
    `export const ${name.replace(/^./, (c) => c.toUpperCase())}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
  writeFileSync(join(outDir, `${name}.ts`), body)
  console.log(`wrote packages/shared/src/abi/${name}.ts (${artifact.abi.length} entries)`)
}
